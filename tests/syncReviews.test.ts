import { beforeEach, describe, expect, it, vi } from "vitest";
import mongoose from "mongoose";

const {
  connectMock,
  locationFindOneMock,
  locationUpdateOneMock,
  reviewFindOneAndUpdateMock,
  reviewFindOneMock,
  reviewFindMock,
  getTokenMock,
  listReviewsMock,
} = vi.hoisted(() => ({
  connectMock: vi.fn(),
  locationFindOneMock: vi.fn(),
  locationUpdateOneMock: vi.fn(),
  reviewFindOneAndUpdateMock: vi.fn(),
  reviewFindOneMock: vi.fn(),
  reviewFindMock: vi.fn(),
  getTokenMock: vi.fn(),
  listReviewsMock: vi.fn(),
}));

vi.mock("@/lib/mongodb", () => ({
  connectToDatabase: connectMock,
}));

vi.mock("@/models/Location", () => ({
  Location: {
    findOne: locationFindOneMock,
    updateOne: locationUpdateOneMock,
  },
}));

vi.mock("@/models/Review", () => ({
  Review: {
    findOneAndUpdate: reviewFindOneAndUpdateMock,
    findOne: reviewFindOneMock,
    find: reviewFindMock,
  },
}));

vi.mock("@/lib/google/accessToken", () => ({
  getValidAccessTokenForContext: getTokenMock,
}));

vi.mock("@/lib/entitlements/enforce", () => ({
  assertReviewSyncAllowed: vi.fn().mockResolvedValue(undefined),
}));

vi.mock("@/lib/reviews/autoDraftOnSync", () => ({
  maybeAutoGenerateDraftsForLocation: vi.fn().mockResolvedValue({
    attempted: 0,
    generated: 0,
    skipped: 0,
    published: false,
  }),
}));

vi.mock("@/models/Business", () => ({
  Business: {
    findById: vi.fn().mockReturnValue({
      select: () => ({
        lean: async () => ({ active: true, status: "active" }),
      }),
    }),
  },
}));

vi.mock("@/lib/google/gbpDiscovery", async () => {
  const actual = await vi.importActual<typeof import("@/lib/google/gbpDiscovery")>(
    "@/lib/google/gbpDiscovery"
  );
  return {
    ...actual,
    listAllReviewsForLocation: listReviewsMock,
  };
});

import { syncReviewsForLocation } from "@/lib/google/syncReviews";
import { GoogleBusinessApiError } from "@/lib/google/gbpErrors";

const ORG_A = new mongoose.Types.ObjectId().toString();
const ORG_B = new mongoose.Types.ObjectId().toString();
const LOC_ID = new mongoose.Types.ObjectId().toString();

describe("syncReviewsForLocation authorization and isolation", () => {
  beforeEach(() => {
    vi.clearAllMocks();
    connectMock.mockResolvedValue({});
    getTokenMock.mockResolvedValue("access-token");
    reviewFindOneAndUpdateMock.mockResolvedValue({});
    reviewFindOneMock.mockReturnValue({
      select: () => ({
        lean: async () => null,
      }),
    });
    locationUpdateOneMock.mockResolvedValue({});
    reviewFindMock.mockReturnValue({
      sort: () => ({
        lean: async () => [],
      }),
    });
  });

  it("rejects when location is not owned by the organization", async () => {
    locationFindOneMock.mockReturnValue({
      exec: async () => null,
    });

    await expect(
      syncReviewsForLocation({ orgId: ORG_A, locationId: LOC_ID })
    ).rejects.toMatchObject({ code: "location_not_found", status: 404 });
    expect(getTokenMock).not.toHaveBeenCalled();
    expect(listReviewsMock).not.toHaveBeenCalled();
  });

  it("scopes the location query to orgId (isolation)", async () => {
    locationFindOneMock.mockReturnValue({
      exec: async () => null,
    });

    await expect(
      syncReviewsForLocation({ orgId: ORG_B, locationId: LOC_ID })
    ).rejects.toMatchObject({ code: "location_not_found" });

    expect(locationFindOneMock).toHaveBeenCalledWith({
      _id: LOC_ID,
      orgId: ORG_B,
    });
  });

  it("upserts reviews for an owned location and clears sync error", async () => {
    locationFindOneMock.mockReturnValue({
      exec: async () => ({
        _id: LOC_ID,
        orgId: ORG_A,
        googleLocationName: "accounts/1/locations/2",
      }),
    });
    listReviewsMock.mockResolvedValue({
      reviews: [
        {
          name: "accounts/1/locations/2/reviews/r1",
          reviewId: "r1",
          reviewer: { displayName: "Alex", isAnonymous: false },
          starRating: "FIVE",
          comment: "Great",
          createTime: "2024-01-01T00:00:00Z",
          updateTime: "2024-01-02T00:00:00Z",
        },
      ],
      totalReviewCount: 1,
    });
    reviewFindMock.mockReturnValue({
      sort: () => ({
        lean: async () => [
          {
            _id: new mongoose.Types.ObjectId(),
            reviewerDisplayName: "Alex",
            starRating: 5,
            comment: "Great",
            createTime: new Date("2024-01-01T00:00:00Z"),
            updateTime: new Date("2024-01-02T00:00:00Z"),
          },
        ],
      }),
    });

    const result = await syncReviewsForLocation({
      orgId: ORG_A,
      locationId: LOC_ID,
    });

    expect(getTokenMock).toHaveBeenCalledWith(
      { orgId: ORG_A, businessId: null },
      expect.any(Function)
    );
    expect(listReviewsMock).toHaveBeenCalledWith(
      "access-token",
      "accounts/1/locations/2",
      expect.any(Function)
    );
    expect(reviewFindOneAndUpdateMock).toHaveBeenCalledWith(
      { orgId: ORG_A, googleReviewName: "accounts/1/locations/2/reviews/r1" },
      expect.objectContaining({
        $set: expect.objectContaining({
          reviewerDisplayName: "Alex",
          starRating: 5,
          comment: "Great",
          replyComment: "",
          replyState: "",
        }),
      }),
      expect.objectContaining({ upsert: true })
    );
    // Unassigned locations must not invent a businessId on sync — explicitly null.
    const upsertArg = reviewFindOneAndUpdateMock.mock.calls[0][1].$set;
    expect(upsertArg.businessId).toBeNull();
    expect(result.upserted).toBe(1);
    expect(result.reviews[0].reviewerDisplayName).toBe("Alex");
  });

  it("propagates location.businessId onto synced reviews when assigned", async () => {
    const BIZ = new mongoose.Types.ObjectId();
    locationFindOneMock.mockReturnValue({
      exec: async () => ({
        _id: LOC_ID,
        orgId: ORG_A,
        businessId: BIZ,
        googleLocationName: "accounts/1/locations/2",
      }),
    });
    listReviewsMock.mockResolvedValue({
      reviews: [
        {
          name: "accounts/1/locations/2/reviews/r2",
          reviewId: "r2",
          reviewer: { displayName: "Pat", isAnonymous: false },
          starRating: "FOUR",
          comment: "Nice",
        },
      ],
      totalReviewCount: 1,
    });

    await syncReviewsForLocation({ orgId: ORG_A, locationId: LOC_ID });

    expect(reviewFindOneAndUpdateMock).toHaveBeenCalledWith(
      { orgId: ORG_A, googleReviewName: "accounts/1/locations/2/reviews/r2" },
      expect.objectContaining({
        $set: expect.objectContaining({
          businessId: BIZ,
          reviewerDisplayName: "Pat",
        }),
      }),
      expect.objectContaining({ upsert: true })
    );
  });

  it("surfaces Google API denial without inventing reviews", async () => {
    locationFindOneMock.mockReturnValue({
      exec: async () => ({
        _id: LOC_ID,
        orgId: ORG_A,
        googleLocationName: "accounts/1/locations/2",
      }),
    });
    listReviewsMock.mockRejectedValue(
      new GoogleBusinessApiError("Google denied access", {
        code: "permission_denied",
        status: 403,
      })
    );

    await expect(
      syncReviewsForLocation({ orgId: ORG_A, locationId: LOC_ID })
    ).rejects.toMatchObject({ code: "permission_denied" });

    expect(reviewFindOneAndUpdateMock).not.toHaveBeenCalled();
    expect(locationUpdateOneMock).toHaveBeenCalledWith(
      { _id: LOC_ID },
      { $set: { lastReviewsSyncError: "permission_denied" } }
    );
  });
});
