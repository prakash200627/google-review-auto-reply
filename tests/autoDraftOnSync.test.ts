import { beforeEach, describe, expect, it, vi } from "vitest";
import mongoose from "mongoose";

const {
  connectMock,
  businessFindByIdMock,
  reviewFindMock,
  reviewUpdateOneMock,
  generateMock,
  isConfiguredMock,
  reserveMock,
} = vi.hoisted(() => ({
  connectMock: vi.fn(),
  businessFindByIdMock: vi.fn(),
  reviewFindMock: vi.fn(),
  reviewUpdateOneMock: vi.fn(),
  generateMock: vi.fn(),
  isConfiguredMock: vi.fn(),
  reserveMock: vi.fn(),
}));

vi.mock("@/lib/mongodb", () => ({
  connectToDatabase: connectMock,
}));

vi.mock("@/models/Business", () => ({
  Business: { findById: businessFindByIdMock },
}));

vi.mock("@/models/Review", () => ({
  Review: {
    find: reviewFindMock,
    updateOne: reviewUpdateOneMock,
  },
}));

vi.mock("@/lib/ai/openaiConfig", () => ({
  isOpenAiConfigured: isConfiguredMock,
}));

vi.mock("@/lib/ai/replyDraft", () => ({
  generateReplyDraft: generateMock,
}));

vi.mock("@/lib/entitlements/enforce", () => ({
  tryReserveAiDraftQuota: reserveMock,
}));

import { maybeAutoGenerateDraftsForLocation } from "@/lib/reviews/autoDraftOnSync";

const ORG = new mongoose.Types.ObjectId().toString();
const LOC = new mongoose.Types.ObjectId().toString();
const BIZ = new mongoose.Types.ObjectId().toString();
const REVIEW = new mongoose.Types.ObjectId();

describe("maybeAutoGenerateDraftsForLocation", () => {
  beforeEach(() => {
    vi.clearAllMocks();
    connectMock.mockResolvedValue({});
    isConfiguredMock.mockReturnValue(true);
    reserveMock.mockResolvedValue(undefined);
    reviewUpdateOneMock.mockResolvedValue({});
    generateMock.mockResolvedValue({
      draft: "Thanks!",
      tone: "positive",
      model: "test",
    });
  });

  it("does nothing when replyMode is manual", async () => {
    businessFindByIdMock.mockReturnValue({
      select: () => ({
        lean: async () => ({
          replyMode: "manual",
          autoDraftOnSync: true,
        }),
      }),
    });
    const result = await maybeAutoGenerateDraftsForLocation({
      orgId: ORG,
      locationId: LOC,
      businessId: BIZ,
    });
    expect(result.generated).toBe(0);
    expect(result.published).toBe(false);
    expect(generateMock).not.toHaveBeenCalled();
  });

  it("generates drafts when auto mode + autoDraftOnSync, never publishes", async () => {
    businessFindByIdMock.mockReturnValue({
      select: () => ({
        lean: async () => ({
          replyMode: "auto",
          autoDraftOnSync: true,
          brandVoice: "friendly",
          preferredLanguage: "English",
          replyToneNotes: "",
        }),
      }),
    });
    reviewFindMock.mockReturnValue({
      select: () => ({
        limit: () => ({
          lean: async () => [
            {
              _id: REVIEW,
              starRating: 5,
              comment: "Nice",
              reviewerDisplayName: "Pat",
            },
          ],
        }),
      }),
    });

    const result = await maybeAutoGenerateDraftsForLocation({
      orgId: ORG,
      locationId: LOC,
      businessId: BIZ,
    });
    expect(result.generated).toBe(1);
    expect(result.published).toBe(false);
    expect(generateMock).toHaveBeenCalled();
    expect(reviewUpdateOneMock).toHaveBeenCalledWith(
      expect.objectContaining({ _id: REVIEW }),
      expect.objectContaining({
        $set: expect.objectContaining({
          draftStatus: "generated",
          draftApproved: false,
        }),
      })
    );
  });

  it("skips when businessId is null (unassigned location)", async () => {
    const result = await maybeAutoGenerateDraftsForLocation({
      orgId: ORG,
      locationId: LOC,
      businessId: null,
    });
    expect(result.attempted).toBe(0);
    expect(businessFindByIdMock).not.toHaveBeenCalled();
  });
});
