type FetchLike = typeof fetch;

export type SafeReviewSummary = {
  id: string;
  reviewerDisplayName: string;
  starRating: number | null;
  comment: string;
  createTime: string | null;
  updateTime: string | null;
  replyComment: string;
  replyUpdateTime: string | null;
  replyState: string;
  /** Persisted AI draft (never auto-published from this field alone). */
  draftText: string;
  draftApproved: boolean;
  draftStatus: string;
};

export function toReviewSummary(doc: {
  _id: mongoose.Types.ObjectId;
  reviewerDisplayName?: string | null;
  starRating?: number | null;
  comment?: string | null;
  createTime?: Date | null;
  updateTime?: Date | null;
  replyComment?: string | null;
  replyUpdateTime?: Date | null;
  replyState?: string | null;
  draftText?: string | null;
  draftApproved?: boolean | null;
  draftStatus?: string | null;
}): SafeReviewSummary {
  return {
    id: String(doc._id),
    reviewerDisplayName: doc.reviewerDisplayName || "",
    starRating:
      typeof doc.starRating === "number" ? doc.starRating : null,
    comment: doc.comment || "",
    createTime: doc.createTime
      ? new Date(doc.createTime).toISOString()
      : null,
    updateTime: doc.updateTime
      ? new Date(doc.updateTime).toISOString()
      : null,
    replyComment: doc.replyComment || "",
    replyUpdateTime: doc.replyUpdateTime
      ? new Date(doc.replyUpdateTime).toISOString()
      : null,
    replyState: doc.replyState || "",
    draftText: typeof doc.draftText === "string" ? doc.draftText : "",
    draftApproved: Boolean(doc.draftApproved),
    draftStatus: typeof doc.draftStatus === "string" ? doc.draftStatus : "",
  };
}

function parseGoogleTime(value: string | undefined): Date | null {
  if (!value) return null;
  const d = new Date(value);
  return Number.isNaN(d.getTime()) ? null : d;
}

/**
 * Fetch reviews from Google for one org-owned location and upsert locally.
 * Read-only against Google (list only — never updateReply/deleteReply).
 */
export async function syncReviewsForLocation(input: {
  orgId: string;
  locationId: string;
  fetchImpl?: FetchLike;
}): Promise<{
  reviews: SafeReviewSummary[];
  upserted: number;
  totalReviewCount: number | null;
  oneStarEscalations: number;
  autoDraftsGenerated: number;
}> {
  const { orgId, locationId, fetchImpl = fetch } = input;

  if (!mongoose.isValidObjectId(orgId) || !mongoose.isValidObjectId(locationId)) {
    throw new GoogleBusinessApiError("Invalid location or organization", {
      code: "invalid_id",
      status: 400,
    });
  }

  await connectToDatabase();

  const location = await Location.findOne({
    _id: locationId,
    orgId,
  }).exec();

  if (!location) {
    throw new GoogleBusinessApiError(
      "Location not found for this organization",
      { code: "location_not_found", status: 404 }
    );
  }

  if (location.businessId) {
    const businessId = String(location.businessId);
    const business = await Business.findById(businessId)
      .select("active status")
      .lean();
    if (business) {
      assertLifecycleAllowsAction(business, "sync");
    }
    await assertReviewSyncAllowed(businessId);
  }

  const accessToken = await getValidAccessTokenForContext(
    {
      orgId,
      businessId: location.businessId ? String(location.businessId) : null,
    },
    fetchImpl
  );

  let googleReviews;
  let totalReviewCount: number | null = null;
  try {
    const listed = await listAllReviewsForLocation(
      accessToken,
      location.googleLocationName,
      fetchImpl
    );
    googleReviews = listed.reviews;
    totalReviewCount = listed.totalReviewCount;
  } catch (err) {
    const message =
      err instanceof GoogleBusinessApiError
        ? err.message
        : "Failed to retrieve reviews from Google";
    await Location.updateOne(
      { _id: location._id },
      {
        $set: {
          lastReviewsSyncError:
            err instanceof GoogleBusinessApiError
              ? err.code
              : "reviews_sync_failed",
        },
      }
    );
    throw err instanceof GoogleBusinessApiError
      ? err
      : new GoogleBusinessApiError(message, {
          code: "reviews_sync_failed",
          status: 502,
        });
  }

  let upserted = 0;
  let oneStarEscalations = 0;
  for (const review of googleReviews) {
    const googleReviewName =
      review.name ||
      (review.reviewId
        ? `${location.googleLocationName}/reviews/${review.reviewId}`
        : "");
    if (!googleReviewName) continue;

    const googleReviewId =
      review.reviewId || googleReviewName.split("/").pop() || googleReviewName;

    const isAnonymous = Boolean(review.reviewer?.isAnonymous);
    const displayName = isAnonymous
      ? "Anonymous"
      : review.reviewer?.displayName || "";

    const replyComment = review.reviewReply?.comment || "";
    const replyUpdateTime = parseGoogleTime(review.reviewReply?.updateTime);
    const replyState = review.reviewReply?.reviewReplyState || "";

    const existing = await Review.findOne({ orgId, googleReviewName })
      .select("replySource tronxPublishedAt replyComment")
      .lean();

    const setFields: Record<string, unknown> = {
      orgId,
      locationId: location._id,
      // Location.businessId is the assignment source of truth (null when unassigned).
      businessId: location.businessId ?? null,
      googleReviewName,
      googleReviewId,
      reviewerDisplayName: displayName,
      reviewerIsAnonymous: isAnonymous,
      starRating: mapStarRating(review.starRating),
      comment: review.comment || "",
      createTime: parseGoogleTime(review.createTime),
      updateTime: parseGoogleTime(review.updateTime),
    };

    // Preserve TRONX-confirmed publication provenance when Google still shows
    // the same reply. Otherwise record synced Google reply as google_synced.
    const existingWasTronx = existing?.replySource === "tronx_published";
    const sameReply =
      existingWasTronx &&
      String(existing?.replyComment || "").trim() === replyComment.trim() &&
      Boolean(replyComment.trim());

    if (sameReply) {
      setFields.replyComment = replyComment;
      setFields.replyUpdateTime = replyUpdateTime;
      setFields.replyState = replyState;
      // keep replySource / tronxPublishedAt
    } else if (replyComment.trim()) {
      setFields.replyComment = replyComment;
      setFields.replyUpdateTime = replyUpdateTime;
      setFields.replyState = replyState;
      setFields.replySource = "google_synced";
      // Do not clear tronxPublishedAt historical marker if it exists, but
      // current reply is no longer attributed as a fresh TRONX publish.
      if (!existingWasTronx) {
        setFields.tronxPublishedAt = null;
      }
    } else {
      setFields.replyComment = "";
      setFields.replyUpdateTime = replyUpdateTime;
      setFields.replyState = replyState;
      if (!existingWasTronx) {
        setFields.replySource = "unknown";
      }
    }

    const saved = await Review.findOneAndUpdate(
      { orgId, googleReviewName },
      { $set: setFields },
      { upsert: true, returnDocument: "after", setDefaultsOnInsert: true }
    );
    upserted += 1;

    // One-star: internal escalation only — never publish / never report to Google.
    if (saved?._id) {
      const esc = await escalateOneStarReview({
        reviewId: String(saved._id),
        businessId: location.businessId
          ? String(location.businessId)
          : null,
        locationId: String(location._id),
        orgId: String(orgId),
        starRating:
          typeof setFields.starRating === "number"
            ? setFields.starRating
            : null,
        comment:
          typeof setFields.comment === "string" ? setFields.comment : "",
      });
      if (esc.flagCreated) oneStarEscalations += 1;
    }
  }

  await Location.updateOne(
    { _id: location._id },
    {
      $set: {
        lastReviewsSyncAt: new Date(),
        lastReviewsSyncError: "",
      },
    }
  );

  // Draft automation only — never publishes. Gated by replyMode=auto + autoDraftOnSync.
  let autoDraftsGenerated = 0;
  try {
    const draftResult = await maybeAutoGenerateDraftsForLocation({
      orgId: String(orgId),
      locationId: String(location._id),
      businessId: location.businessId ? String(location.businessId) : null,
    });
    autoDraftsGenerated = draftResult.generated;
  } catch (err) {
    console.error(
      "Auto-draft after sync failed (sync still succeeded):",
      err instanceof Error ? err.message : "unknown error"
    );
  }

  const stored = await Review.find({ orgId, locationId: location._id })
    .sort({ updateTime: -1, createTime: -1 })
    .lean();

  return {
    reviews: stored.map(toReviewSummary),
    upserted,
    totalReviewCount,
    oneStarEscalations,
    autoDraftsGenerated,
  };
}

export async function listStoredReviewsForLocation(input: {
  orgId: string;
  locationId: string;
}): Promise<SafeReviewSummary[]> {
  const { orgId, locationId } = input;
  if (!mongoose.isValidObjectId(orgId) || !mongoose.isValidObjectId(locationId)) {
    return [];
  }

  await connectToDatabase();

  const location = await Location.findOne({ _id: locationId, orgId })
    .select("_id")
    .lean();
  if (!location) {
    throw new GoogleBusinessApiError(
      "Location not found for this organization",
      { code: "location_not_found", status: 404 }
    );
  }

  const stored = await Review.find({ orgId, locationId })
    .sort({ updateTime: -1, createTime: -1 })
    .lean();
  return stored.map(toReviewSummary);
}
