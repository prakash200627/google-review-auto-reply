/**
 * Safe draft automation after review sync.
 * - Only runs when Business.replyMode === "auto" AND autoDraftOnSync === true.
 * - Never publishes to Google.
 * - Skips reviews that already have a public reply or an approved draft.
 * - Best-effort; failures are logged and never fail the sync.
 */

import mongoose from "mongoose";
import { generateReplyDraft } from "@/lib/ai/replyDraft";
import { isOpenAiConfigured } from "@/lib/ai/openaiConfig";
import { tryReserveAiDraftQuota } from "@/lib/entitlements/enforce";
import { connectToDatabase } from "@/lib/mongodb";
import { Business } from "@/models/Business";
import { Review } from "@/models/Review";

export type AutoDraftOnSyncResult = {
  attempted: number;
  generated: number;
  skipped: number;
  published: false;
};

export async function maybeAutoGenerateDraftsForLocation(input: {
  orgId: string;
  locationId: string;
  businessId: string | null;
}): Promise<AutoDraftOnSyncResult> {
  const empty: AutoDraftOnSyncResult = {
    attempted: 0,
    generated: 0,
    skipped: 0,
    published: false,
  };

  if (
    !input.businessId ||
    !mongoose.isValidObjectId(input.businessId) ||
    !mongoose.isValidObjectId(input.locationId)
  ) {
    return empty;
  }
  if (!isOpenAiConfigured()) return empty;

  await connectToDatabase();
  const business = await Business.findById(input.businessId)
    .select(
      "replyMode autoDraftOnSync brandVoice preferredLanguage replyToneNotes active status plan"
    )
    .lean();
  if (!business) return empty;
  if (business.replyMode !== "auto" || business.autoDraftOnSync !== true) {
    return empty;
  }

  const candidates = await Review.find({
    orgId: input.orgId,
    locationId: input.locationId,
    businessId: input.businessId,
    draftApproved: { $ne: true },
    $and: [
      {
        $or: [
          { replyComment: { $exists: false } },
          { replyComment: "" },
          { replyComment: null },
        ],
      },
      {
        $or: [
          { draftText: { $exists: false } },
          { draftText: "" },
          { draftText: null },
        ],
      },
    ],
  })
    .select(
      "_id starRating comment reviewerDisplayName draftText draftStatus draftApproved"
    )
    .limit(10)
    .lean();

  let generated = 0;
  let skipped = 0;
  for (const review of candidates) {
    try {
      await tryReserveAiDraftQuota(input.businessId);
      const result = await generateReplyDraft({
        starRating:
          typeof review.starRating === "number" ? review.starRating : null,
        comment: review.comment || "",
        reviewerDisplayName: review.reviewerDisplayName || "",
        brandVoice: business.brandVoice || "friendly",
        preferredLanguage: business.preferredLanguage || "English",
        replyToneNotes: String(business.replyToneNotes || ""),
      });
      const now = new Date();
      await Review.updateOne(
        { _id: review._id, draftApproved: { $ne: true } },
        {
          $set: {
            draftText: result.draft,
            draftStatus: "generated",
            draftApproved: false,
            draftGeneratedAt: now,
            draftUpdatedAt: now,
          },
        }
      );
      generated += 1;
    } catch {
      skipped += 1;
    }
  }

  return {
    attempted: candidates.length,
    generated,
    skipped,
    published: false,
  };
}
